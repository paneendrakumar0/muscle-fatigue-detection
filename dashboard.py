import streamlit as st
import pandas as pd
import numpy as np
import time
import joblib
import plotly.graph_objs as go
from feature_extraction import extract_emg_features, extract_imu_features
from data_generation import generate_synthetic_data

st.set_page_config(page_title="Muscle Fatigue Dashboard", layout="wide")
st.title("Real-Time Muscle Fatigue Classification Dashboard")

@st.cache_resource
def load_model():
    return joblib.load('fatigue_model.pkl')

@st.cache_data
def get_stream_data():
    # Generate 1 minute of data for the streaming simulation
    return generate_synthetic_data(duration_minutes=1)

model = load_model()
df_stream = get_stream_data()

fs = 200
window_size = 200 # 1 second window

col1, col2 = st.columns([1, 4])
with col1:
    start_btn = st.button("Start Streaming")
    stop_btn = st.button("Stop Streaming")
    
with col2:
    placeholder_state = st.empty()

placeholder_emg = st.empty()
placeholder_imu = st.empty()

if start_btn:
    for i in range(0, len(df_stream) - window_size, int(fs/4)):  # update every 0.25s
        if stop_btn:
            break
            
        window = df_stream.iloc[i:i+window_size]
        
        # Predict
        emg_raw = window['emg_raw'].values
        accel_x, accel_y, accel_z = window['accel_x'].values, window['accel_y'].values, window['accel_z'].values
        gyro_x, gyro_y, gyro_z = window['gyro_x'].values, window['gyro_y'].values, window['gyro_z'].values
        
        emg_feats = extract_emg_features(emg_raw, fs)
        imu_feats = extract_imu_features(accel_x, accel_y, accel_z, gyro_x, gyro_y, gyro_z)
        
        feature_dict = {**emg_feats, **imu_feats}
        for key in feature_dict:
            feature_dict[key] = [feature_dict[key]]
            
        features_df = pd.DataFrame(feature_dict)
        pred = model.predict(features_df)[0]
        actual = window['label'].mode()[0]
        
        # Plot EMG
        fig_emg = go.Figure()
        fig_emg.add_trace(go.Scatter(y=emg_raw, mode='lines', name='EMG Raw', line=dict(color='royalblue')))
        fig_emg.update_layout(title="EMG Signal (Last 1 Second)", yaxis_range=[-1.5, 1.5], height=300, margin=dict(l=20, r=20, t=40, b=20))
        
        # Plot Accel
        fig_imu = go.Figure()
        fig_imu.add_trace(go.Scatter(y=accel_x, mode='lines', name='Accel X'))
        fig_imu.add_trace(go.Scatter(y=accel_y, mode='lines', name='Accel Y'))
        fig_imu.add_trace(go.Scatter(y=accel_z, mode='lines', name='Accel Z'))
        fig_imu.update_layout(title="Acceleration (Tremor indicator)", yaxis_range=[-2, 12], height=300, margin=dict(l=20, r=20, t=40, b=20))
        
        # Update Dashboard Elements
        color = "green" if pred == "Rested" else "orange" if pred == "Fatiguing" else "red"
        
        state_html = f"""
        <div style='background-color: #f0f2f6; padding: 10px; border-radius: 10px; text-align: center; border-left: 10px solid {color};'>
            <h2 style='margin:0;'>Live Prediction: <span style='color: {color};'>{pred}</span></h2>
            <p style='margin:0;'>Ground Truth Label: {actual}</p>
        </div>
        """
        placeholder_state.markdown(state_html, unsafe_allow_html=True)
        
        placeholder_emg.plotly_chart(fig_emg, use_container_width=True)
        placeholder_imu.plotly_chart(fig_imu, use_container_width=True)
        
        time.sleep(0.1) # Simulate real-time delay

st.markdown("---")
st.markdown("*Simulation pulling data generated by `data_generation.py`, calculating features via `feature_extraction.py`, and inferring using the saved `fatigue_model.pkl`.*")
